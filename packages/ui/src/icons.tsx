import type { SVGProps } from 'react';

/**
 * The app's one icon set.
 *
 * ## Rules (docs/DESIGN-LANGUAGE.md §5.5)
 *
 * - **Geometry**: 24×24 grid, 1.7 stroke, round caps and joins. Every path is
 *   taken from [Lucide](https://lucide.dev) (ISC licence) rather than drawn by
 *   hand. Two hand-drawn gears were shipped before this rule existed and both
 *   read wrong at 18px — teeth need flat flanks, and that is not something to
 *   re-derive per icon.
 * - **Colour**: `currentColor` and nothing else. An icon takes its colour from
 *   the control around it, so hover/focus/disabled states need no icon rules.
 * - **Stroke width scales with the box** (below): a 16px icon drawn at 1.7
 *   looks bolder than a 24px one at the same weight, because the stroke is a
 *   fixed fraction of a smaller grid.
 * - **Accessibility**: `aria-hidden` always. The *control* carries the name
 *   (`aria-label` or visible text), never the svg.
 *
 * ## Adding an icon
 *
 * Copy the path data from Lucide's source, keep the 24 grid, and check it at
 * 14 / 16 / 18 / 24px in both themes. Do not invent a path.
 */
type IconProps = SVGProps<SVGSVGElement> & { size?: number };

/**
 * Stroke width per rendered size.
 *
 * The 1.7 default is calibrated for 18px. Scaling it inversely keeps the
 * *optical* weight constant: a 14px icon gets a slightly fatter relative
 * stroke, a 24px one slightly thinner.
 */
function strokeFor(size: number): number {
  if (size <= 14) return 1.9;
  if (size <= 16) return 1.8;
  if (size <= 18) return 1.7;
  return 1.6;
}

function Svg({ size = 18, strokeWidth, children, ...rest }: IconProps) {
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={strokeWidth ?? strokeFor(size)}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      {...rest}
    >
      {children}
    </svg>
  );
}

